/** El idioma del atributo `lang`, o el de la página; español si no es inglés. */
export const langOf = (el) => {
  const l = (el.getAttribute('lang') || document.documentElement.lang || navigator.language || 'es').slice(0, 2)
  return l === 'en' ? 'en' : 'es'
}

export const escapeHtml = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))
